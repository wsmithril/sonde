/// The URI scheme prefix a URI AD structure (0x24) opens with. The scheme is a
/// SIG code point encoded as one UTF-8 character, so it is read as a character
/// rather than a byte — codes above 0x7F take two bytes on air. Returns the
/// scheme name and the byte length it occupied.
fn uri_scheme(data: &[u8]) -> Option<(&'static str, usize)> {
    let s = core::str::from_utf8(data).ok()?;
    let c = s.chars().next()?;
    let name = lookup(URI_SCHEMES, u16::try_from(c as u32).ok()?)?;
    Some((name, c.len_utf8()))
}

