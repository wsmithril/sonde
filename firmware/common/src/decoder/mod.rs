/// Append the set major service-class flags (Class of Device bits 23..13).
fn write_cod_services(s: &mut LogStr, cod: u32) {
    use core::fmt::Write;
    const SVC: [(u32, &str); 11] = [
        (13, "LimitedDiscoverable"),
        (14, "LE-Audio"),
        (15, "Reserved"),
        (16, "Positioning"),
        (17, "Networking"),
        (18, "Rendering"),
        (19, "Capturing"),
        (20, "ObjectTransfer"),
        (21, "Audio"),
        (22, "Telephony"),
        (23, "Information"),
    ];
    let mut first = true;
    for (bit, name) in SVC {
        if cod & (1 << bit) != 0 {
            let _ = write!(s, "{}{}", if first { " [" } else { " " }, name);
            first = false;
        }
    }
    if !first { let _ = write!(s, "]"); }
}

/// Append an advertising interval given in 0.625 ms units as milliseconds with
/// two decimal places (`0x00A0` → `100.00ms`).
fn write_interval(s: &mut LogStr, units: u32) {
    use core::fmt::Write;
    let us = units * 625;
    let _ = write!(s, "{}.{:02}ms", us / 1000, (us % 1000) / 10);
}

pub fn write_hex(s: &mut LogStr, data: &[u8]) {
    use core::fmt::Write;
    for b in data {
        let _ = write!(s, "{:02X}", b);
    }
}

/// Emit `data` as a multi-line hexdump (classic `hexdump -C` style): up to 16
/// space-separated bytes per line in two groups of eight, then an ASCII gutter
/// where printable bytes
/// (0x20..=0x7E) render as themselves and everything else as '.'. Each line is
/// prefixed with `p{XX}:r{XX}:` where `p` is the byte offset within the decoded
/// field (`base` + block offset) and `r` is the offset within this hex block.
/// The hex column is padded on a short final row so the ASCII gutter stays
/// aligned. Breaking long blobs across lines keeps every line well under the
/// buffer cap, so no line can overflow and lose its terminator. Emits nothing
/// when `data` is empty.
pub fn hexdump(data: &[u8], base: usize, indent: usize) {
    use core::fmt::Write;
    // Classify every byte for the gutter once, over the whole payload, so a
    // multi-byte UTF-8 character that straddles a 16-byte line boundary renders
    // correctly: its lead byte shows the glyph on one line, and its continuation
    // bytes show `·` (GUT_CONT) on the following line. Classes: GUT_START (first
    // byte of a printable UTF-8 char), GUT_CONT (a following byte of one), or
    // GUT_DOT (a control char or a byte that is not valid UTF-8).
    let mut cls = [GUT_DOT; 256];
    let n = data.len().min(cls.len());
    let mut i = 0;
    while i < n {
        match core::str::from_utf8(&data[i..n]) {
            Ok(s) => {
                classify_gutter(s, i, &mut cls);
                break;
            }
            Err(e) => {
                let vu = e.valid_up_to();
                if vu > 0
                    && let Ok(s) = core::str::from_utf8(&data[i..i + vu])
                {
                    classify_gutter(s, i, &mut cls);
                }
                match e.error_len() {
                    Some(l) => i += vu + l,
                    None => break,
                }
            }
        }
    }

    for (row, chunk) in data.chunks(16).enumerate() {
        let rel = row * 16;
        let mut s: LogStr = LogStr::new();
        for _ in 0..indent {
            let _ = s.push(' ');
        }
        let _ = write!(s, "p{:02X}:r{:02X}: ", base + rel, rel);
        for (k, b) in chunk.iter().enumerate() {
            // Bytes run together within each half; a single space at the halfway
            // mark, as `hexdump -C` does, gives the eye a fixed landmark to count
            // from so picking byte 11 out of a row is two short counts rather than
            // one long one.
            if k == 8 {
                let _ = s.push(' ');
            }
            let _ = write!(s, "{:02X}", b);
        }
        // Pad the hex column (2 chars/byte, plus the halfway space if this row
        // stopped before it) so the ASCII gutter aligns on a short final row.
        for _ in 0..(16 - chunk.len()) {
            let _ = s.push_str("  ");
        }
        if chunk.len() <= 8 {
            let _ = s.push(' ');
        }
        let _ = s.push_str("  ");
        for (k, &b) in chunk.iter().enumerate() {
            let pos = rel + k;
            let g = if pos < n { cls[pos] } else { GUT_DOT };
            let c = match g {
                GUT_START => {
                    // Re-decode the one char that starts at this byte.
                    let end = (pos + utf8_len(b)).min(n);
                    core::str::from_utf8(&data[pos..end])
                        .ok()
                        .and_then(|t| t.chars().next())
                        .unwrap_or('.')
                }
                GUT_CONT => '·',
                _ => '.',
            };
            let _ = s.push(c);
        }
        emit(s);
    }
}

// Byte classes for the hexdump gutter.
const GUT_DOT: u8 = 0;
const GUT_CONT: u8 = 1;
const GUT_START: u8 = 2;

/// Mark the byte classes for the printable characters in `s` (a valid-UTF-8 run
/// that begins at byte `seg_base` of the payload) into `cls`. Control characters
/// are left as `GUT_DOT`.
fn classify_gutter(s: &str, seg_base: usize, cls: &mut [u8]) {
    for (off, c) in s.char_indices() {
        let g = seg_base + off;
        if g >= cls.len() {
            break;
        }
        if c.is_control() {
            continue; // leave as GUT_DOT
        }
        cls[g] = GUT_START;
        for j in 1..c.len_utf8() {
            if g + j < cls.len() {
                cls[g + j] = GUT_CONT;
            }
        }
    }
}

/// Number of bytes in the UTF-8 sequence whose lead byte is `b` (1 for ASCII).
fn utf8_len(b: u8) -> usize {
    if b < 0x80 {
        1
    } else if b >= 0xF0 {
        4
    } else if b >= 0xE0 {
        3
    } else {
        2
    }
}

/// Whether the advertiser's own 6-byte address appears anywhere in `data`, in
/// either byte order. `adva` is the on-air (little-endian) address; payloads
/// carry it both that way round and in display order.
fn contains_addr(data: &[u8], adva: &[u8; 6]) -> bool {
    let mut rev = *adva;
    rev.reverse();
    data.windows(6).any(|w| w == adva.as_slice() || w == rev.as_slice())
}

