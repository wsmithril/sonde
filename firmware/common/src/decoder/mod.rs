/// Walk every AD structure in `adv_data` and log one decoded line each.
///
/// AdvData is a sequence of AD structures, each `[len][type][data (len-1 bytes)]`.
/// Returns how many bytes of `adv_data` the walk accounted for. The caller
/// hex-dumps the remainder and nothing else — see [`crate::mode::ble_sniff`] — so a
/// packet whose structures all decode gets no dump, and one with a few bytes of
/// tail junk gets one short line instead of the whole payload again.
///
/// A trailing run of zeros counts as accounted for: a zero length byte is the
/// spec's end-of-data marker and the padding after it carries nothing. Anything
/// else the walk stops on — a length running past the buffer, a stray byte too
/// short to be a structure — does not, because that is exactly the case where
/// the raw bytes are the only record of what arrived.
/// `verified` is the frame's CRC status. On an unverified (CRC-salvaged) frame
/// the AD-structure boundaries still walk clean — that is the salvage gate — but
/// the field *contents* are unproven, so the deeper vendor sub-decoders (Apple
/// Continuity, mesh bearers, service-data decoders) are skipped and their bodies
/// dumped raw. Running them on corrupt bytes invents phantom sub-messages.
pub fn log_ad_structures(adv_data: &[u8], adva: Option<[u8; 6]>, verified: bool) -> usize {
    use core::fmt::Write;

    // Bytes consumed by complete structures; the walk's stopping point.
    let mut consumed = 0usize;

    // Synthesised into one `profile:` line after the walk. A frame whose whole
    // payload is a service-UUID list gets no vendor decode, so this is the only
    // thing that says a bare 0x1812 advertiser is a HID peripheral.
    let mut roles: heapless::Vec<&'static str, 8> = heapless::Vec::new();
    let mut appearance: Option<u16> = None;

    let mut i = 0;
    while i + 1 < adv_data.len() {
        let field_len = adv_data[i] as usize;
        if field_len == 0 {
            // End-of-data marker. The rest is padding when it is all zeros, and
            // padding is accounted for; a non-zero tail is not.
            if adv_data[i..].iter().all(|&b| b == 0) {
                consumed = adv_data.len();
            }
            break;
        }
        let data_end = i + 1 + field_len; // length byte covers type + data
        if data_end > adv_data.len() { break; } // truncated structure
        let ad_type = adv_data[i + 1];
        let data = &adv_data[i + 2..data_end];

        // Some cheap beacons stuff their own 6-byte BD_ADDR into the manufacturer
        // field, so the "Company ID" is just the low two bytes of the MAC. Detect
        // this so we flag it instead of reporting a bogus vendor.
        let mfg_is_own_addr =
            ad_type == 0xFF && matches!(adva, Some(a) if data == a.as_slice());

        // A whole family of cheap IoT beacons (e-bikes/scooters, GPS trackers)
        // put two octets of their *own* address into the 2-byte Company-ID slot
        // — an unregistered ID that happens to equal part of the MAC (e.g. addr
        // A1:4A:… advertises Company-ID 0x4AA1). `adva` is the on-air
        // little-endian address, so a[5],a[4] are the leading display octets and
        // a[0],a[1] the trailing pair; both ends turn up in captures. This is a
        // fingerprint/privacy leak and protocol misuse, not a real vendor.
        let mfg_cid_is_own_prefix = ad_type == 0xFF
            && data.len() >= 2
            && !mfg_is_own_addr
            && matches!(adva, Some(a) if (data[0] == a[5] && data[1] == a[4])
                                      || (data[0] == a[0] && data[1] == a[1]));

        // Others carry the whole address somewhere inside the body instead of at
        // its start, so the Company ID looks legitimate while the frame still
        // republishes the identity the rotating address is supposed to hide.
        let mfg_body_has_own_addr = ad_type == 0xFF
            && !mfg_is_own_addr
            && matches!(adva, Some(a) if contains_addr(data, &a));

        let mut s: LogStr = LogStr::new();
        let _ = write!(s, "  {} (0x{:02X}): ", ad_type_name(ad_type), ad_type);

        // Raw byte blobs are not printed inline (they overflow long lines);
        // instead the arm records `(bytes, field-offset)` here and we hexdump
        // them on their own lines after the header line is emitted.
        let mut tail: Option<(&[u8], usize)> = None;

        // Container/list arms (MfgData, ServiceData, multi-entry UUID lists) emit
        // their own header + indented children and set this, so the generic
        // single-line emit + tail dump below is skipped for them.
        let mut handled = false;

        match ad_type {
            0x01 => {
                // Flags bitfield.
                let f = data.first().copied().unwrap_or(0);
                let _ = write!(s, "0x{:02X}", f);
                if f & 0x01 != 0 { let _ = write!(s, " LE-Limited"); }
                if f & 0x02 != 0 { let _ = write!(s, " LE-General"); }
                if f & 0x04 != 0 { let _ = write!(s, " NoBREDR"); }
                if f & 0x08 != 0 { let _ = write!(s, " LE+BREDR-Ctrl"); }
                // Bit 4 named the host half of the same simultaneous-LE/BR-EDR
                // capability until the SIG withdrew it; CSS Part A Table 1.4
                // now reads "Previously Used". Stacks predating the withdrawal
                // still set it, so it is worth showing under a name that does
                // not claim a capability the spec no longer defines.
                if f & 0x10 != 0 { let _ = write!(s, " PreviouslyUsed"); }
            }
            0x08 | 0x09 => {
                // Local name (UTF-8, else hex).
                match core::str::from_utf8(data) {
                    Ok(n)  => { let _ = write!(s, "{}", n); }
                    Err(_) => tail = Some((data, 0)),
                }
            }
            0x0A => {
                // TX power, signed dBm.
                let p = data.first().copied().unwrap_or(0) as i8;
                let _ = write!(s, "{} dBm", p);
            }
            0x19 => {
                // Appearance, u16 little-endian.
                if data.len() >= 2 {
                    let a = u16::from_le_bytes([data[0], data[1]]);
                    appearance = Some(a);
                    let _ = write!(s, "0x{:04X} ({})", a, appearance_name(a));
                } else {
                    tail = Some((data, 0));
                }
            }
            0x02 | 0x03 | 0x14 => {
                // 16-bit UUID list — annotate assigned SIG UUIDs with their name.
                // Two or more break into a dashed child list; a single UUID stays
                // inline on the header line.
                if data.len() / 2 >= 2 {
                    emit_ad_header(ad_type);
                    for pair in data.chunks(2) {
                        if pair.len() == 2 {
                            let u = u16::from_le_bytes([pair[0], pair[1]]);
                            push_role(&mut roles, u);
                            let mut c: LogStr = LogStr::new();
                            let _ = write!(c, "    - {:04X} ", u);
                            write_uuid_name(&mut c, u);
                            emit(c);
                        }
                    }
                    handled = true;
                } else {
                    for pair in data.chunks(2) {
                        if pair.len() == 2 {
                            let u = u16::from_le_bytes([pair[0], pair[1]]);
                            push_role(&mut roles, u);
                            let _ = write!(s, "{:04X} ", u);
                            write_uuid_name(&mut s, u);
                        }
                    }
                }
            }
            0x04 | 0x05 | 0x1F => {
                // 32-bit UUID list.
                if data.len() / 4 >= 2 {
                    emit_ad_header(ad_type);
                    for q in data.chunks(4) {
                        if q.len() == 4 {
                            let mut c: LogStr = LogStr::new();
                            let _ = write!(c, "    - {:08X}",
                                u32::from_le_bytes([q[0], q[1], q[2], q[3]]));
                            emit(c);
                        }
                    }
                    handled = true;
                } else {
                    for q in data.chunks(4) {
                        if q.len() == 4 {
                            let _ = write!(s, "{:08X} ", u32::from_le_bytes([q[0], q[1], q[2], q[3]]));
                        }
                    }
                }
            }
            0x06 | 0x07 | 0x15 => {
                // 128-bit UUID list — transmitted LE, print MSB-first.
                if data.len() / 16 >= 2 {
                    emit_ad_header(ad_type);
                    for chunk in data.chunks(16) {
                        if chunk.len() == 16 {
                            let mut c: LogStr = LogStr::new();
                            let _ = write!(c, "    - ");
                            for b in chunk.iter().rev() {
                                let _ = write!(c, "{:02X}", b);
                            }
                            emit(c);
                        }
                    }
                    handled = true;
                } else {
                    for chunk in data.chunks(16) {
                        for b in chunk.iter().rev() {
                            let _ = write!(s, "{:02X}", b);
                        }
                        let _ = write!(s, " ");
                    }
                }
            }
            0x16 if data.len() >= 2 => {
                // Service data, 16-bit UUID prefix — a container: UUID on its own
                // child line, then the service-specific decode (or a raw body dump
                // if the UUID is unknown).
                let u = u16::from_le_bytes([data[0], data[1]]);
                push_role(&mut roles, u);
                emit_ad_header(ad_type);
                let mut c: LogStr = LogStr::new();
                let _ = write!(c, "    uuid={:04X} ", u);
                write_uuid_name(&mut c, u);
                let _ = write!(c, "len={}", data.len() - 2);
                emit(c);
                if verified {
                    advert::decode_service_data(data, adva);
                } else {
                    hexdump(&data[2..], 2, 6);
                }
                handled = true;
            }
            0x0D => {
                // Class of Device (3 bytes, LE): service-class bits (23..13),
                // major device class (12..8), minor device class (7..2).
                if data.len() >= 3 {
                    let cod = u32::from_le_bytes([data[0], data[1], data[2], 0]);
                    let _ = write!(s, "0x{:06X} {}", cod, cod_major(((cod >> 8) & 0x1F) as u8));
                    write_cod_services(&mut s, cod);
                } else {
                    tail = Some((data, 0));
                }
            }
            0x24 => {
                // URI: the scheme goes out as a SIG code point rather than
                // spelled out, so it is expanded here and the remainder of the
                // field is the rest of the URI as UTF-8.
                match (uri_scheme(data), core::str::from_utf8(data)) {
                    (Some((scheme, n)), Ok(u)) => { let _ = write!(s, "{}{}", scheme, &u[n..]); }
                    (None, Ok(u)) => { let _ = write!(s, "{}", u); }
                    _ => tail = Some((data, 0)),
                }
            }
            0x20 if data.len() >= 4 => {
                // Service data, 32-bit UUID prefix — a container: UUID on its own
                // child line, then the raw body dump.
                emit_ad_header(ad_type);
                let mut c: LogStr = LogStr::new();
                let _ = write!(c, "    uuid={:08X} len={}",
                    u32::from_le_bytes([data[0], data[1], data[2], data[3]]),
                    data.len() - 4);
                emit(c);
                hexdump(&data[4..], 4, 6);
                handled = true;
            }
            0x21 if data.len() >= 16 => {
                // Service data, 128-bit UUID prefix — transmitted LE, print
                // MSB-first so it reads as the canonical UUID. A container: UUID on
                // its own child line, then the raw body dump.
                emit_ad_header(ad_type);
                let mut c: LogStr = LogStr::new();
                let _ = write!(c, "    uuid=");
                for b in data[..16].iter().rev() {
                    let _ = write!(c, "{:02X}", b);
                }
                let _ = write!(c, " len={}", data.len() - 16);
                emit(c);
                hexdump(&data[16..], 16, 6);
                handled = true;
            }
            0x1B => {
                // LE Bluetooth Device Address: the identity address, 6 bytes LE
                // plus a type octet. Published under a rotating RPA it defeats
                // the rotation, so it is worth naming explicitly.
                if data.len() >= 7 {
                    let a = &data[..6];
                    let _ = write!(s, "{:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X} {}",
                        a[5], a[4], a[3], a[2], a[1], a[0],
                        if data[6] & 1 == 0 { "public" } else { "random" });
                } else {
                    tail = Some((data, 0));
                }
            }
            0x17 | 0x18 => {
                // Target address list — one or more 6-byte addresses, each LE.
                // Two or more break into a dashed child list; a single address
                // stays inline on the header line.
                if data.len() / 6 >= 2 {
                    emit_ad_header(ad_type);
                    for a in data.chunks(6) {
                        if a.len() == 6 {
                            let mut c: LogStr = LogStr::new();
                            let _ = write!(c, "    - {:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X}",
                                a[5], a[4], a[3], a[2], a[1], a[0]);
                            emit(c);
                        }
                    }
                    handled = true;
                } else {
                    for a in data.chunks(6) {
                        if a.len() == 6 {
                            let _ = write!(s, "{:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X} ",
                                a[5], a[4], a[3], a[2], a[1], a[0]);
                        }
                    }
                }
            }
            0x1C => {
                // LE Role, one octet.
                if let Some(&r) = data.first() {
                    let _ = write!(s, "0x{:02X} ({})", r, le_role_name(r));
                } else {
                    tail = Some((data, 0));
                }
            }
            0x1A => {
                // Advertising Interval, u16 LE in 0.625 ms units.
                if data.len() >= 2 {
                    write_interval(&mut s, u16::from_le_bytes([data[0], data[1]]) as u32);
                } else {
                    tail = Some((data, 0));
                }
            }
            0x2F => {
                // Advertising Interval - long: 3 or 4 octets LE, 0.625 ms units.
                match data.len() {
                    3 => write_interval(&mut s, u32::from_le_bytes([data[0], data[1], data[2], 0])),
                    4 => write_interval(&mut s, u32::from_le_bytes([data[0], data[1], data[2], data[3]])),
                    _ => tail = Some((data, 0)),
                }
            }
            0x2E => {
                // Resolvable Set Identifier (CSIP): SIRK hash (3 octets) then
                // the random it was derived from (3 octets), both LE. Only a set
                // member holding the SIRK can resolve it, but the pair is stable
                // for as long as `prand` is reused.
                if data.len() >= 6 {
                    let _ = write!(s, "hash={:02X}{:02X}{:02X} prand={:02X}{:02X}{:02X}",
                        data[2], data[1], data[0], data[5], data[4], data[3]);
                    // Set correlation (#9): with a matching SIRK compiled in, tag
                    // the coordinated-set this member belongs to. Off unless built
                    // with `resolve-identities`.
                    #[cfg(feature = "resolve-identities")]
                    {
                        let prand = [data[5], data[4], data[3]];
                        let hash = [data[2], data[1], data[0]];
                        for (sirk, label) in crate::keys::SIRKS {
                            if crate::hal::crypto::ah(sirk, &prand) == hash {
                                let _ = write!(s, " set={}", label);
                                break;
                            }
                        }
                    }
                } else {
                    tail = Some((data, 0));
                }
            }
            0x30 => {
                // Broadcast_Name (LE Audio), UTF-8.
                match core::str::from_utf8(data) {
                    Ok(n)  => { let _ = write!(s, "{}", n); }
                    Err(_) => tail = Some((data, 0)),
                }
            }
            0x28 => {
                // Channel Map Update Indication: 5-octet channel map then the
                // connection event instant it takes effect at (u16 LE).
                if data.len() >= 7 {
                    let used: u32 = data[..5].iter().map(|b| b.count_ones()).sum();
                    let _ = write!(s, "chmap={:02X}{:02X}{:02X}{:02X}{:02X} ({} ch) instant={}",
                        data[0], data[1], data[2], data[3], data[4], used,
                        u16::from_le_bytes([data[5], data[6]]));
                } else {
                    tail = Some((data, 0));
                }
            }
            0x27 => {
                // LE Supported Features, a little-endian bitfield of whatever
                // length the advertiser chose to send.
                let _ = write!(s, "0x");
                for b in data.iter().rev() {
                    let _ = write!(s, "{:02X}", b);
                }
            }
            0x2C => {
                // BIGInfo (rides in periodic ACAD): the Broadcast Isochronous
                // Group parameters a receiver needs to sync to an Auracast /
                // LE-Audio broadcast stream.
                biginfo_summary(&mut s, data);
            }
            0x31 => {
                // Encrypted Advertising Data (Core v5.4 Vol 3 Part C §11):
                // 5-byte Randomizer, ciphertext, 4-byte MIC. Undecryptable
                // without the session key, but the layout is worth surfacing.
                if data.len() >= 9 {
                    let mic = &data[data.len() - 4..];
                    let _ = write!(s,
                        "randomizer={:02X}{:02X}{:02X}{:02X}{:02X} payload={}B mic={:02X}{:02X}{:02X}{:02X}",
                        data[0], data[1], data[2], data[3], data[4], data.len() - 9,
                        mic[0], mic[1], mic[2], mic[3]);
                } else {
                    tail = Some((data, 0));
                }
            }
            0xFF if mfg_is_own_addr => {
                // The field equals the advertiser's own address — not a vendor.
                let _ = write!(s, "own-address (not a vendor)");
                tail = Some((data, 0));
            }
            // Manufacturer-specific: first 2 bytes = Company ID (LE). Too short
            // for one and it falls through to the catch-all, which dumps the
            // bytes as they came. A container: the company on its own child line,
            // then the vendor deep-decode (or a raw body dump if unknown).
            0xFF if data.len() >= 2 => {
                let cid = u16::from_le_bytes([data[0], data[1]]);
                emit_ad_header(ad_type);
                let mut c: LogStr = LogStr::new();
                let _ = write!(c, "    ");
                if mfg_cid_is_own_prefix {
                    // Company-ID == own MAC prefix: not a vendor, a privacy leak.
                    let _ = write!(c, "0x{:04X} (own-MAC-prefix, unregistered) ", cid);
                } else {
                    match company_name(cid) {
                        Some(n) => { let _ = write!(c, "{} (0x{:04X}) ", n, cid); }
                        // 0xFFFF is the SIG "no company / internal use" value.
                        None if cid == 0xFFFF => {
                            let _ = write!(c, "0xFFFF (reserved/test — not a real company) ");
                        }
                        None => {
                            let _ = write!(c, "0x{:04X} (unregistered", cid);
                            // Some makers type two characters into the
                            // Company-ID slot as a brand tag rather than
                            // registering: 0x5944 is the ASCII "DY". The
                            // bytes go out little-endian, so data[0] is the
                            // first character.
                            if data[0].is_ascii_graphic() && data[1].is_ascii_graphic() {
                                let _ = write!(c, ", ascii \"{}{}\"",
                                    data[0] as char, data[1] as char);
                            }
                            let _ = write!(c, ") ");
                        }
                    }
                }
                let _ = write!(c, "len={}", data.len() - 2);
                emit(c);
                if mfg_body_has_own_addr {
                    let mut n: LogStr = LogStr::new();
                    let _ = write!(n, "    own address embedded in manufacturer data (identity leak)");
                    emit(n);
                }
                if mfg_cid_is_own_prefix || !verified {
                    // Not a vendor, or a CRC-salvaged frame whose body is unproven —
                    // show the raw body under the container instead of running a
                    // vendor decoder that would invent phantom sub-messages.
                    hexdump(&data[2..], 2, 6);
                } else {
                    advert::decode_mfg(data);
                }
                handled = true;
            }
            _ => {
                tail = Some((data, 0));
            }
        }

        // Inline (non-container) types: one header line, then their unparsed tail
        // one level deeper. Container/list arms already emitted everything above.
        if !handled {
            if let Some((t, _)) = tail
                && !t.is_empty()
            {
                let _ = write!(s, " len={}", t.len());
            }
            emit(s);
            if let Some((t, b)) = tail {
                hexdump(t, b, 4);
            }

            // Mesh advertising bearers carry their own PDU formats, decoded below
            // the header line — but only on a CRC-verified frame; on salvage the
            // tail hexdump above is all that can be trusted.
            if verified {
                match ad_type {
                    0x29 => advert::mesh::decode_pb_adv(data),
                    0x2A => advert::mesh::decode_message(data),
                    0x2B => advert::mesh::decode_beacon(data),
                    _ => {}
                }
            }
        }
        i = data_end;
        consumed = i;
    }

    // Appearance alone repeats the 0x19 line, so the summary needs at least one
    // service role to be worth a line of its own.
    if !roles.is_empty() {
        let mut s: LogStr = LogStr::new();
        let _ = write!(s, "  profile:");
        for (k, r) in roles.iter().enumerate() {
            let _ = write!(s, "{} {}", if k == 0 { "" } else { "," }, r);
        }
        if let Some(a) = appearance {
            let _ = write!(s, " · appearance {} (0x{:04X})", appearance_name(a), a);
        }
        emit(s);
    }

    consumed
}

/// Read `n` bits (LSB-first) starting at bit offset `bo` from a little-endian
/// bitstream. Used to unpack the tightly-packed BIGInfo field.
fn bits_le(d: &[u8], bo: usize, n: usize) -> u64 {
    let mut v = 0u64;
    for i in 0..n {
        let bit = bo + i;
        if d.get(bit / 8).is_some_and(|b| (b >> (bit % 8)) & 1 != 0) {
            v |= 1 << i;
        }
    }
    v
}

/// Summarise a BIGInfo (AD 0x2C) field — the LL Broadcast Isochronous Group
/// parameters (Core v5.4 Vol 6 Part B §2.3.4.9) that a receiver needs to sync to
/// an LE-Audio / Auracast broadcast. Unencrypted BIGInfo is 33 bytes, encrypted
/// is 57 (the trailing GIV/GSKD present only when encrypted).
fn biginfo_summary(s: &mut LogStr, d: &[u8]) {
    use core::fmt::Write;
    if d.len() < 33 {
        let _ = write!(s, "truncated ({}B)", d.len());
        return;
    }
    let num_bis = bits_le(d, 27, 5);
    let iso_x100 = bits_le(d, 15, 12) * 125; // Iso_Interval, 1.25 ms units → ms×100
    let sdu_interval = bits_le(d, 136, 20); // µs
    let max_pdu = bits_le(d, 88, 8);
    let max_sdu = bits_le(d, 156, 12);
    let seed_aa = bits_le(d, 104, 32) as u32;
    let phy = bits_le(d, 221, 3);
    let framing = bits_le(d, 263, 1);
    let phy_s = match phy {
        1 => "1M",
        2 => "2M",
        4 => "Coded",
        _ => "?",
    };
    let _ = write!(
        s,
        "bis={} iso={}.{:02}ms sdu={}us max_pdu={} max_sdu={} phy={} {} seed_aa=0x{:08X} enc={}",
        num_bis,
        iso_x100 / 100,
        iso_x100 % 100,
        sdu_interval,
        max_pdu,
        max_sdu,
        phy_s,
        if framing == 1 { "framed" } else { "unframed" },
        seed_aa,
        if d.len() >= 57 { "yes" } else { "no" }
    );
}

/// Parsed `CONNECT_IND` LLData — everything needed to follow the connection onto
/// the data channels. Time fields keep their on-air units: `win_size`,
/// `win_offset`, `interval` are in 1.25 ms steps; `timeout` in 10 ms steps.
#[derive(Clone, Copy)]
pub struct ConnSpec {
    pub aa: u32,
    pub crc_init: u32,
    pub win_size: u8,
    pub win_offset: u16,
    pub interval: u16,
    pub latency: u16,
    pub timeout: u16,
    pub chm: [u8; 5],
    pub hop: u8,
    pub sca: u8,
    /// ChSel from the PDU header: the link hops with Channel Selection
    /// Algorithm #2 rather than #1.
    ///
    /// The initiator sets this bit only when the advertiser also advertised
    /// CSA#2 support, so the one bit in the `CONNECT_IND` header decides the
    /// algorithm for the whole connection. `hop` still carries a value in
    /// 5..=16 either way; CSA#2 leaves it unused.
    pub csa2: bool,
}

impl ConnSpec {
    /// Whether these LLData values are within the ranges the Core spec permits,
    /// i.e. whether this describes a connection that can actually be followed.
    ///
    /// Parsing a `CONNECT_IND` cannot fail on content — the fields are just
    /// bytes — so a corrupted reception yields a perfectly well-formed
    /// [`ConnSpec`] full of nonsense. Committing to one means scheduling the
    /// first event a minute into the future and holding the radio there, so the
    /// follower must range-check before it accepts the timeline.
    ///
    /// Ranges are Core v5.4 Vol 6 Part B §2.3.3.1 (`connInterval` 7.5 ms–4 s,
    /// `connSlaveLatency` ≤ 499, `connSupervisionTimeout` 100 ms–32 s and
    /// greater than `(1 + latency) × interval × 2`, `hopIncrement` 5–16,
    /// `transmitWindowSize` ≤ min(10 ms, interval − 1.25 ms)) plus §4.5.8.1's
    /// requirement of at least two used data channels.
    pub fn is_followable(&self) -> bool {
        let ch_count: u32 = self.chm.iter().map(|b| b.count_ones()).sum();
        // Units: interval/win_* are 1.25 ms steps, timeout is 10 ms steps, so
        // the timeout comparison is done in 1.25 ms steps (×8).
        (6..=3200).contains(&self.interval)
            && self.latency <= 499
            && (10..=3200).contains(&self.timeout)
            && (self.timeout as u32) * 8 > (1 + self.latency as u32) * (self.interval as u32) * 2
            && (5..=16).contains(&self.hop)
            && self.win_size >= 1
            && (self.win_size as u16) <= core::cmp::min(8, self.interval - 1)
            && self.win_offset <= self.interval
            && self.chm[4] & 0xE0 == 0 // bits 37..39 are RFU and must be zero
            && ch_count >= 2
            && access_address_valid(self.aa)
    }
}

/// Core v5.4 Vol 6 Part B §2.1.2 validity rules for a data-channel access
/// address. Cheap and worth applying: a random 32-bit value from a corrupted
/// reception fails these far more often than not, and following a bogus AA wedges
/// the receiver on an address nothing will ever transmit.
fn access_address_valid(aa: u32) -> bool {
    if aa == 0x8E89_BED6 {
        return false; // the advertising access address
    }
    let b = aa.to_le_bytes();
    if b[0] == b[1] && b[1] == b[2] && b[2] == b[3] {
        return false; // all four octets equal
    }
    // No more than six consecutive identical bits, and at least two transitions
    // in the six most significant bits.
    let mut run = 1u32;
    let mut msb_transitions = 0u32;
    for i in 1..32 {
        let prev = (aa >> (i - 1)) & 1;
        let cur = (aa >> i) & 1;
        if cur == prev {
            run += 1;
            if run > 6 {
                return false;
            }
        } else {
            run = 1;
            if i >= 27 {
                msb_transitions += 1;
            }
        }
    }
    msb_transitions >= 2
}

/// Parse a `CONNECT_IND` payload (`InitA[6] AdvA[6] LLData[22]`) into a
/// [`ConnSpec`]. `payload` starts at InitA (i.e. `buf[2..]`); needs ≥34 bytes.
/// `hdr` is the PDU header byte (`buf[0]`), which carries ChSel in bit 5.
pub fn parse_connect_ind(hdr: u8, payload: &[u8]) -> Option<ConnSpec> {
    if payload.len() < 34 { return None; }
    let ll = &payload[12..34]; // LLData
    Some(ConnSpec {
        aa: u32::from_le_bytes([ll[0], ll[1], ll[2], ll[3]]),
        crc_init: ll[4] as u32 | (ll[5] as u32) << 8 | (ll[6] as u32) << 16,
        win_size: ll[7],
        win_offset: u16::from_le_bytes([ll[8], ll[9]]),
        interval: u16::from_le_bytes([ll[10], ll[11]]),
        latency: u16::from_le_bytes([ll[12], ll[13]]),
        timeout: u16::from_le_bytes([ll[14], ll[15]]),
        chm: [ll[16], ll[17], ll[18], ll[19], ll[20]],
        hop: ll[21] & 0x1F,
        sca: ll[21] >> 5,
        csa2: hdr & 0x20 != 0,
    })
}

/// Decode a `CONNECT_IND` payload into labeled lines. Every field is plaintext —
/// the PDU is sent before the link is encrypted — and the LLData carries exactly
/// what a sniffer needs to follow the connection onto the data channels: Access
/// Address, CRCInit, channel map and hop increment, plus the link timing
/// parameters. `payload` starts at InitA (i.e. `buf[2..]`); needs ≥34 bytes.
/// `hdr` is the PDU header byte (`buf[0]`), the source of the ChSel bit.
pub fn decode_connect_ind(hdr: u8, payload: &[u8]) -> bool {
    use core::fmt::Write;
    let spec = match parse_connect_ind(hdr, payload) {
        Some(s) => s,
        None => return false,
    };
    let init = &payload[0..6];   // Initiator (the central) — on-air LE
    let adva = &payload[6..12];  // Advertiser (the peripheral) — on-air LE
    let ch_count: u32 = spec.chm.iter().map(|b| b.count_ones()).sum();

    // 1.25 ms units → hundredths of a ms (×125) for a "NN.MMms" render.
    let iv = spec.interval as u32 * 125;
    let ws = spec.win_size as u32 * 125;
    let wo = spec.win_offset as u32 * 125;

    let mut s: LogStr = LogStr::new();
    let _ = write!(s, "    InitA={:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X} -> AdvA={:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X}",
        init[5], init[4], init[3], init[2], init[1], init[0],
        adva[5], adva[4], adva[3], adva[2], adva[1], adva[0]);
    emit(s);
    let mut s: LogStr = LogStr::new();
    // `csa` is the hop algorithm the pair will use — the field that says whether
    // the channel sequence follows `hop` at all.
    let _ = write!(s, "    AA=0x{:08X} CRCInit=0x{:06X} hop={} sca={} csa={}",
        spec.aa, spec.crc_init, spec.hop, spec.sca, if spec.csa2 { 2 } else { 1 });
    emit(s);
    let mut s: LogStr = LogStr::new();
    let _ = write!(s, "    interval={}.{:02}ms latency={} timeout={}ms",
        iv / 100, iv % 100, spec.latency, spec.timeout as u32 * 10);
    emit(s);
    let mut s: LogStr = LogStr::new();
    // ChM in spec octet order: chm[0] bit 0 is channel 0, so the leftmost hex
    // byte covers channels 0-7. This used to print chm[4]..chm[0] — reversed,
    // like a big-endian integer. It is self-consistent but reads exactly like
    // wire order, and it caused a live misdiagnosis: a capture showing
    // "0CF6C00000" was decoded by hand as channels {2,3,9,10,12,13,14,15,22,23}
    // when the follower was correctly hopping {22,23,25,26,28,29,30,31,34,35},
    // making a working channel map look like the bug.
    let _ = write!(s, "    winsize={}.{:02}ms winoffset={}.{:02}ms chmap={:02X}{:02X}{:02X}{:02X}{:02X} ({} ch)",
        ws / 100, ws % 100, wo / 100, wo % 100,
        spec.chm[0], spec.chm[1], spec.chm[2], spec.chm[3], spec.chm[4], ch_count);
    emit(s);
    true
}


// ── Extended advertising (BLE 5) decoder ─────────────────────────────────────
//
// ADV_EXT_IND and friends use the Common Extended Advertising Payload Format:
//   [ExtHdrLen:6 | AdvMode:2] [Extended Header] [AdvData]
// The extended header is a 1-byte flags field followed by the present fields in
// a fixed order, then optional ACAD. Fields we recognise are decoded; the rest
// (CTEInfo, SyncInfo, ACAD) are skipped, and any trailing AdvData is handed to
// the normal AD-structure decoder. When the walk cannot account for the whole
// payload it reports so via `ExtInfo::ok`, and the caller hex-dumps the raw
// bytes instead.
/// AuxPtr extracted from an extended-advertising header: where (data channel
/// index + PHY) and when (µs offset from the packet start) the aux packet airs.
/// `phy`: 0 = LE 1M, 1 = LE 2M, 2 = LE Coded.
pub struct AuxPtr {
    pub chan: u8,
    pub phy: u8,
    pub offset_us: u32,
}

/// SyncInfo extracted from an `AUX_ADV_IND` header: everything needed to receive
/// the advertiser's periodic advertising train (`AUX_SYNC_IND` + chained
/// `AUX_CHAIN_IND` on the data channels selected by CSA#2 on the periodic AA).
/// `offset_us == 0` means the offset was too far to represent → unschedulable.
#[derive(Clone, Copy)]
pub struct SyncInfo {
    pub offset_us: u32,     // to the AUX_SYNC_IND, from this packet's air-start
    pub interval_125us: u16, // periodic advertising interval, 1.25 ms units
    pub chm: [u8; 5],        // 37-bit periodic channel map
    pub aa: u32,             // periodic Access Address
    pub crc_init: u32,       // 24-bit CRCInit
    pub event_counter: u16,  // paEventCounter of the AUX_SYNC_IND the offset points to
}

/// Actionable fields the scanner needs from an extended-advertising header.
#[derive(Default)]
pub struct ExtInfo {
    pub aux: Option<AuxPtr>,
    pub adi: Option<u16>,
    pub sync: Option<SyncInfo>,
    /// Whether the walk accounted for the whole payload — header well-formed and
    /// any ACAD/AdvData decoded cleanly. Drives the caller's fall back to a raw
    /// hex dump. Only meaningful on the logging walk ([`decode_ext_adv`]); the
    /// silent walk ([`parse_ext_hdr`]) never touches AdvData and leaves it false.
    pub ok: bool,
}

/// Extract [`ExtInfo`] from an extended-advertising payload, silently.
///
/// Serves the sniffer's capture path, which needs the AuxPtr immediately — an aux
/// packet can air only ~300 µs later. [`decode_ext_adv`] prints the same header
/// later, off that path; both share one walker so the two agree.
pub fn parse_ext_hdr(p: &[u8]) -> ExtInfo {
    walk_ext_hdr(p, false)
}

/// Decode an extended-advertising payload, logging each header field and any
/// trailing AdvData, and return its [`ExtInfo`].
pub fn decode_ext_adv(p: &[u8]) -> ExtInfo {
    walk_ext_hdr(p, true)
}

/// Shared extended-header walk. `log` selects whether each recognised field is
/// also emitted; the returned [`ExtInfo`] is identical either way.
fn walk_ext_hdr(p: &[u8], log: bool) -> ExtInfo {
    use core::fmt::Write;
    let mut info = ExtInfo::default();
    if p.is_empty() { return info; }

    let ext_hdr_len = (p[0] & 0x3F) as usize;
    if log {
        let adv_mode = match p[0] >> 6 {
            0 => "non-conn/non-scan",
            1 => "connectable",
            2 => "scannable",
            _ => "rfu",
        };
        let mut s: LogStr = LogStr::new();
        let _ = write!(s, "  ExtHdr: mode={} hdrlen={}\r\n", adv_mode, ext_hdr_len);
        emit(s);
        // Provisionally decoded; the ACAD/AdvData walks below can revoke it, as
        // can a header claiming more bytes than the packet holds.
        // The header ends at `1 + ext_hdr_len`; that must be inside the packet.
        info.ok = ext_hdr_len < p.len();
    }

    // Walk the extended header fields when present (ext_hdr_len covers the flags
    // byte + fields + ACAD; AdvData starts at 1 + ext_hdr_len).
    if ext_hdr_len >= 1 && p.len() > 1 {
        let flags = p[1];
        let mut off = 2;

        // AdvA (6 bytes, little-endian on air).
        if flags & 0x01 != 0 && off + 6 <= p.len() {
            if log {
                let a = &p[off..off + 6];
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr AdvA: {:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X}\r\n",
                    a[5], a[4], a[3], a[2], a[1], a[0]);
                emit(s);
            }
            off += 6;
        }
        // TargetA (6 bytes).
        if flags & 0x02 != 0 && off + 6 <= p.len() {
            if log {
                let a = &p[off..off + 6];
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr TargetA: {:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X}\r\n",
                    a[5], a[4], a[3], a[2], a[1], a[0]);
                emit(s);
            }
            off += 6;
        }
        // CTEInfo (1 byte): CTE Time (bits 0-4, 8µs units) + CTE Type (bits 6-7).
        if flags & 0x04 != 0 && off < p.len() {
            if log {
                let cte = p[off];
                let time_us = (cte & 0x1F) as u32 * 8;
                let typ = match (cte >> 6) & 0x03 {
                    0 => "AoA",
                    1 => "AoD-1us",
                    2 => "AoD-2us",
                    _ => "rfu",
                };
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr CTEInfo: type={} time={}us\r\n", typ, time_us);
                emit(s);
            }
            off += 1;
        }
        // ADI (2 bytes): DID (low 12 bits) + SID (high 4 bits).
        if flags & 0x08 != 0 && off + 2 <= p.len() {
            let adi = u16::from_le_bytes([p[off], p[off + 1]]);
            info.adi = Some(adi);
            if log {
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr ADI: did=0x{:03X} sid=0x{:X}\r\n",
                    adi & 0x0FFF, adi >> 12);
                emit(s);
            }
            off += 2;
        }
        // AuxPtr (3 bytes): channel, offset units/value, and PHY of the aux packet.
        if flags & 0x10 != 0 && off + 3 <= p.len() {
            let chan    = p[off] & 0x3F;
            let units   = if p[off] & 0x80 != 0 { 300u32 } else { 30 }; // µs
            let raw     = u16::from_le_bytes([p[off + 1], p[off + 2]]);
            let aux_off = (raw & 0x1FFF) as u32 * units;
            let phy_num = (p[off + 2] >> 5) & 0x07;
            info.aux = Some(AuxPtr { chan, phy: phy_num, offset_us: aux_off });
            if log {
                let phy = match phy_num {
                    0 => "1M", 1 => "2M", 2 => "Coded", _ => "?",
                };
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr AuxPtr: ch={} phy={} offset={}us\r\n",
                    chan, phy, aux_off);
                emit(s);
            }
            off += 3;
        }
        // SyncInfo (18 bytes, all little-endian): the periodic advertising sync
        // parameters (Core v5.4 Vol 6 Part B §2.3.4.6).
        if flags & 0x20 != 0 && off + 18 <= p.len() {
            let si = &p[off..off + 18];
            let w0 = u16::from_le_bytes([si[0], si[1]]);
            let sync_off = (w0 & 0x1FFF) as u32; // SyncPacketOffset (0 = too far)
            let units = if w0 & 0x2000 != 0 { 300u32 } else { 30 }; // OffsetUnits
            let adjust = if w0 & 0x4000 != 0 { 2_457_600u32 } else { 0 }; // OffsetAdjust
            let offset_us = if sync_off == 0 { 0 } else { sync_off * units + adjust };
            let interval_125us = u16::from_le_bytes([si[2], si[3]]);
            let chm = [si[4], si[5], si[6], si[7], si[8] & 0x1F];
            let sca = (si[8] >> 5) & 0x07;
            let aa = u32::from_le_bytes([si[9], si[10], si[11], si[12]]);
            let crc_init = u32::from_le_bytes([si[13], si[14], si[15], 0]);
            let event_counter = u16::from_le_bytes([si[16], si[17]]);
            info.sync = Some(SyncInfo {
                offset_us, interval_125us, chm, aa, crc_init, event_counter,
            });
            if log {
                let ms_x100 = interval_125us as u32 * 125;
                let mut s: LogStr = LogStr::new();
                let _ = write!(s,
                    "  ExtHdr SyncInfo: aa=0x{:08X} crcinit=0x{:06X} interval={}.{:02}ms offset={}us evt={} sca={} chm={:02X}{:02X}{:02X}{:02X}{:02X}\r\n",
                    aa, crc_init, ms_x100 / 100, ms_x100 % 100, offset_us, event_counter,
                    sca, chm[0], chm[1], chm[2], chm[3], chm[4]);
                emit(s);
            }
            off += 18;
        }
        // TxPower (1 byte, signed dBm).
        if flags & 0x40 != 0 && off < p.len() {
            if log {
                let mut s: LogStr = LogStr::new();
                let _ = write!(s, "  ExtHdr TxPower: {} dBm\r\n", p[off] as i8);
                emit(s);
            }
            off += 1;
        }

        // ACAD (Additional Controller Advertising Data): whatever remains between
        // the last present field and AdvData is a run of AD structures (BIGInfo,
        // ChannelMapUpdateInd…). Decode it the same way as AdvData.
        let hdr_end = 1 + ext_hdr_len;
        if log && off < hdr_end && hdr_end <= p.len() {
            let acad = &p[off..hdr_end];
            let mut s: LogStr = LogStr::new();
            let _ = write!(s, "  ExtHdr ACAD ({} B):\r\n", acad.len());
            emit(s);
            info.ok &= log_ad_structures(acad, None, true) == acad.len();
        }
    }

    // AdvData (standard AD structures) follows the extended header.
    let adv_data_start = 1 + ext_hdr_len;
    if log && adv_data_start < p.len() {
        // Ext-adv AdvA lives in the extended header (not at a fixed payload
        // offset), so the own-address check is not applied here.
        let adv_data = &p[adv_data_start..];
        info.ok &= log_ad_structures(adv_data, None, true) == adv_data.len();
    }

    info
}
