//! BLE advertising decoders.
//!
//! `log_ad_structures` walks the AD-structure list of a legacy advertising PDU
//! and `decode_ext_adv` handles the BLE-5 extended-advertising header; both emit
//! one readable log line per field and fall back to a hex dump for anything not
//! recognised. Vendor- and service-specific deep decoders live in the submodules
//! below and are reached through the `decode_mfg` / `decode_service_data`
//! dispatchers. Only plaintext, structured fields are decoded; identity fields
//! that vendors encrypt/hash/rotate for privacy are labelled but left as hex.

pub mod asset;
/// Advertising-payload deep decoders, dispatched by Company ID / service UUID.
mod advert;
/// Link-layer and L2CAP-borne protocol decoders for connected links.
pub mod protocol;

/// Fixed-capacity log line. Decoders format into this and hand it to `emit`.
pub type LogStr = crate::LogLine;

/// Queue a finished log line for the USB serial task. Never blocks; the line is
/// dropped if the channel is full (host not draining). Long decoded lines can
/// fill the buffer and lose their "\r\n"; `terminate_line` repairs that so lines
/// never run together.
pub fn emit(mut s: LogStr) {
    crate::terminate_line(&mut s);
    // Route to the active render sink if one is set (inside `write_text_to`),
    // else straight to the LOG channel as before. Reading the raw pointer is sound
    // for the same reason `LOG_STAMP` is: decode is synchronous (no `.await`
    // between a `SinkScope` being set and dropped) on the cooperative executor.
    match unsafe { *CUR_SINK.0.get() } {
        Some(vt) => (vt.line)(vt.data, &s),
        None => crate::log_send(s),
    }
}

// Active render sink as a thin (data pointer, line function) pair — a hand-rolled
// one-method vtable, so no `dyn` object and no fat-pointer/lifetime transmute. The
// raw `data` pointer carries no lifetime; it is valid only for the synchronous
// span of a `SinkScope`.
#[derive(Clone, Copy)]
struct SinkRef {
    data: core::ptr::NonNull<()>,
    line: fn(core::ptr::NonNull<()>, &str),
}
struct CurSink(core::cell::UnsafeCell<Option<SinkRef>>);
unsafe impl Sync for CurSink {}
static CUR_SINK: CurSink = CurSink(core::cell::UnsafeCell::new(None));

/// RAII guard that points [`emit`] at `sink` for the current decode, restoring
/// the previous sink (usually none) on drop. Held across a single, `.await`-free
/// decode of one packet — see [`crate::mode::ble_sniff::Decoded::write_text_to`].
pub struct SinkScope(Option<SinkRef>);

impl SinkScope {
    pub fn new<S: crate::Sink>(sink: &mut S) -> Self {
        fn call<S: crate::Sink>(p: core::ptr::NonNull<()>, s: &str) {
            // Sound: `p` came from a live `&mut S` and is only called within the
            // scope that stored it (decode is synchronous, no `.await` between).
            unsafe { p.cast::<S>().as_mut().line(s) }
        }
        let vt = SinkRef {
            data: core::ptr::NonNull::from(sink).cast::<()>(),
            line: call::<S>,
        };
        let prev = unsafe { (*CUR_SINK.0.get()).replace(vt) };
        SinkScope(prev)
    }
}

impl Drop for SinkScope {
    fn drop(&mut self) {
        unsafe { *CUR_SINK.0.get() = self.0 }
    }
}

