/// Record `u`'s role once, keeping the first-seen order.
fn push_role(roles: &mut heapless::Vec<&'static str, 8>, u: u16) {
    if let Some(r) = service_role(u)
        && !roles.contains(&r)
    {
        let _ = roles.push(r);
    }
}

