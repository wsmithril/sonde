/// Binary-search a sorted `(u16, &str)` SIG table.
fn lookup(table: &'static [(u16, &'static str)], id: u16) -> Option<&'static str> {
    table.binary_search_by_key(&id, |&(k, _)| k).ok().map(|i| table[i].1)
}

/// Look up a Bluetooth SIG Company Identifier (the manufacturer-data prefix)
/// in the full SIG registry. `None` for ids not present or unprovisioned.
///
/// Two ids are intercepted before the registry, because the registry answer for
/// them is worse than no answer:
///
/// * `0x0000` really is Ericsson Technology Licensing — the very first entry the
///   SIG ever assigned — but a manufacturer-data field opening `00 00` is nearly
///   always an uninitialised or padded id, not an Ericsson product. The
///   2026-08-02 capture had no plausible Ericsson device in it.
/// * `0xFFFF` is reserved by the SIG for internal/testing use and is what an
///   integrator ships when they never applied for an id (306 devices in that
///   same capture). Naming it as such is the useful decode.
pub fn company_name(id: u16) -> Option<&'static str> {
    match id {
        0x0000 => Some("unset/invalid company ID"),
        0xFFFF => Some("no assigned company ID (SIG reserved 0xFFFF)"),
        _ => asset::company_name(id),
    }
}

/// Look up the IEEE vendor for a public MAC: `prefix` is the 24-bit OUI (the top
/// three octets) and `ext12` the 12 bits below it, which name the assignee when
/// IEEE has subdivided that OUI. Returns the org name in a stack buffer, `None`
/// if unassigned or unprovisioned.
pub fn oui_vendor(prefix: u32, ext12: Option<u16>) -> Option<heapless::String<96>> {
    // 00:00:00 is assigned to Xerox and FF:FF:FF is the broadcast prefix; an
    // address starting with either is an unset field, not a device from those
    // vendors. Answering the registry question honestly here would attach a
    // confident, wrong manufacturer to every zeroed address in the log.
    if prefix == 0x00_0000 || prefix == 0xFF_FFFF {
        return None;
    }
    asset::oui_vendor(prefix, ext12)
}

/// Print a 6-byte MAC-48 held in display (MSB-first) order as `AA:BB:…:FF`.
/// Vendor payloads that embed an address mostly carry it this way round, unlike
/// the packet header's AdvA, which goes out LSB-first.
pub fn write_mac_be(s: &mut LogStr, m: &[u8]) {
    use core::fmt::Write;
    for (i, b) in m.iter().enumerate() {
        if i > 0 { let _ = write!(s, ":"); }
        let _ = write!(s, "{:02X}", b);
    }
}

/// Emit an `    oui: <org>` line naming the IEEE holder of `m`'s top three
/// octets (display order). An address embedded in a payload is a stable
/// identifier even when the advertising address rotates, so its assignee is
/// worth resolving. Emits nothing for a locally administered address (bit 1 of
/// the first octet), which carries no IEEE assignment, or for an unassigned OUI.
///
/// A payload carrying at least five octets also resolves subdivided blocks,
/// where the 24-bit OUI alone names only the registrar.
pub fn emit_oui_vendor(m: &[u8]) {
    use core::fmt::Write;
    if m.len() < 3 || m[0] & 0x02 != 0 { return; }
    let prefix = (m[0] as u32) << 16 | (m[1] as u32) << 8 | m[2] as u32;
    let ext12 = (m.len() >= 5).then(|| (m[3] as u16) << 4 | (m[4] >> 4) as u16);
    if let Some(v) = oui_vendor(prefix, ext12) {
        let mut s: LogStr = LogStr::new();
        let _ = write!(s, "    oui: {}", v);
        emit(s);
    }
}

