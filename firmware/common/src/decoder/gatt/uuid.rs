/// Format a UUID (16-bit or 128-bit) plus any known name into a log fragment.
pub(crate) fn write_uuid(s: &mut LogStr, uuid_le: &[u8]) {
    if uuid_le.len() == 2 {
        let u = u16::from_le_bytes([uuid_le[0], uuid_le[1]]);
        let _ = write!(s, "0x{:04X}", u);
        if let Some(n) = uuid16_name(u) {
            let _ = write!(s, " ({})", n);
        }
    } else if let Some(u) = base_uuid_16(uuid_le) {
        // A 16-bit UUID a peer widened to the full Bluetooth base UUID; show and
        // name it as the 16-bit it really is rather than 32 hex digits.
        let _ = write!(s, "0x{:04X}", u);
        if let Some(n) = uuid16_name(u) {
            let _ = write!(s, " ({})", n);
        }
    } else {
        // 128-bit UUID, big-endian display.
        let _ = s.push_str("0x");
        for b in uuid_le.iter().rev() {
            let _ = write!(s, "{:02X}", b);
        }
        // The on-air bytes are little-endian; reverse them to the display
        // (big-endian) order the name table is written in, then look up.
        if uuid_le.len() == 16 {
            let mut be = [0u8; 16];
            for (i, b) in uuid_le.iter().rev().enumerate() {
                be[i] = *b;
            }
            if let Some(n) = uuid128_name(&be) {
                let _ = write!(s, " ({})", n);
            }
        }
    }
}
