//! GATT UUID naming: map 16-bit and 128-bit attribute UUIDs to human labels, and
//! format a UUID (with its name) for the enumeration log.

use core::fmt::Write;

use crate::decoder::LogStr;

/// If a 128-bit UUID is a 16-bit UUID widened to the Bluetooth Base UUID, return
/// the 16-bit value. The base UUID in on-air (little-endian) order, with the two
/// 16-bit-value bytes at [12..14] left out and the top two bytes at [14..16] zero.
fn base_uuid_16(uuid_le: &[u8]) -> Option<u16> {
    const BASE_LE: [u8; 12] =
        [0xFB, 0x34, 0x9B, 0x5F, 0x80, 0x00, 0x00, 0x80, 0x00, 0x10, 0x00, 0x00];
    if uuid_le.len() == 16 && uuid_le[..12] == BASE_LE && uuid_le[14] == 0 && uuid_le[15] == 0 {
        Some(u16::from_le_bytes([uuid_le[12], uuid_le[13]]))
    } else {
        None
    }
}

/// Name for a well-known 16-bit GATT UUID: declarations, descriptors, services
/// and characteristics.
///
/// The shared [`crate::decoder::uuid_name`] table is built from the SIG's own
/// `uuids/*.yaml` (~1,100 names, refreshed by `scripts/refresh_data.py`); a small
/// vendor shortlist that is *not* SIG-assigned, or that deserves a more specific
/// label than the SIG's, is matched here first.
pub(crate) fn uuid16_name(u: u16) -> Option<&'static str> {
    // U-tec / ULTRALOQ vendor GATT UUIDs (0x72xx range, sent as the Bluetooth
    // base-UUID short form). Which key characteristic a lock exposes reveals its
    // auth handshake (static vs MD5 vs ECC). UUIDs from the utecio library:
    // https://github.com/inventor7777/ultraloq-ble-ha
    let vendor = match u {
        0x7200 => Some("U-tec Lock"),
        0x7201 => Some("U-tec Data"),
        0x7220 => Some("U-tec Key (static)"),
        0x7221 => Some("U-tec Key (ECC)"),
        0x7223 => Some("U-tec Key (MD5)"),
        // Google member services, named more specifically than the SIG table's bare
        // "Google LLC". FE2C = Fast Pair; FEF3 = Nearby Connections / Quick Share
        // (its chars are the uWeave transport, see [`uuid128_name`]); FCF1 = the
        // Play Services container (here surfacing a Fast Pair char).
        0xFE2C => Some("Google Fast Pair"),
        0xFEF3 => Some("Google Nearby/Quick Share"),
        0xFCF1 => Some("Google Play Services"),
        // Amazon FE03 = Alexa Mobile Accessory (AMA) service, more specific than the
        // SIG table's bare "Amazon.com Services, Inc.".
        0xFE03 => Some("Amazon Alexa (AMA)"),
        _ => None,
    };
    vendor.or_else(|| crate::decoder::uuid_name(u))
}

